"""Regenerate the checked-in public MDUI color roles using the actual preview SDK.
Run a production build and serve it before this optional maintenance command:
python scripts/capture-brand-palette.py http://127.0.0.1:4321/
Python Playwright + Chromium are test/maintenance tools, never build dependencies.
"""
import asyncio, json, os, re, sys
from pathlib import Path
from playwright.async_api import async_playwright

ROOT = Path(__file__).resolve().parents[1]
URL = (sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:4321/').rstrip('/') + '/'

async def main():
    design = (ROOT / 'src/lib/design.mjs').read_text()
    color = re.search(r'brandColor\s*=\s*"(#[\da-fA-F]{6})"', design).group(1)
    async with async_playwright() as p:
        browser = await p.chromium.launch(executable_path=os.environ.get('BROWSER_PATH', '/usr/bin/chromium'), args=['--no-sandbox'])
        page = await browser.new_page()
        await page.goto(URL + 'preview/colors/', wait_until='networkidle')
        await page.wait_for_function('document.documentElement.dataset.paletteReady === "true"')
        await page.evaluate('''color => window.postMessage({type:'nekomi:palette:update',palette:{color,secondary:'',mode:'auto'}},location.origin)''', color)
        await page.wait_for_timeout(100)
        result = await page.evaluate('''() => {
          const styles = document.querySelectorAll('style[id^="mdui-custom-color-scheme-"]');
          if (styles.length !== 1) throw Error('Expected one public MDUI palette');
          return {css:styles[0].textContent,className:styles[0].id};
        }''')
        (ROOT / 'src/styles/brand-palette.css').write_text(f'/* Generated by MDUI 2.1.5 public setColorScheme("{color}"). Do not hand-edit. */\n' + result['css'])
        (ROOT / 'src/lib/design.mjs').write_text(f'export const brandColor = {json.dumps(color)};\nexport const brandPaletteClass = {json.dumps(result["className"])};\n')
        print('Captured public MDUI palette:', result['className'])
        await browser.close()

asyncio.run(main())
